#!/usr/bin/env bash
# Generate a Rector config for the new minimum PHP version and run it (dry run by default).

if [[ "${1:-}" == "--help" || $# -lt 2 ]]; then
    cat >&2 <<'EOF'
Usage: rector.sh --floor <min-php> [--apply] [--allow-risky] [--only RuleShortOrFqcn]

  --floor        new minimum PHP version; Rector applies every PHP set up to it (withPhpSets)
                 and never introduces syntax above it (withPhpVersion)
  --apply        write the changes, repeating passes (max 5) until a pass changes nothing;
                 prints {"passes": [summary...], "converged": bool} (default: dry run)
  --allow-risky  do not skip the risky rules listed in references/rector.md
  --only         run a single rule (repeatable is not supported; run several times)
Also enables withComposerBased(phpunit: true) and withAttributesSets(phpunit: true), which read the
INSTALLED PHPUnit version — upgrade and install PHPUnit first.
Config: <state>/rector.php. Report: <state>/reports/rector.json. Prints a JSON summary.
Exit (dry run) 0 nothing to change, 1 changes pending; (apply) 0 converged, 1 not converged after 5 passes;
2 Rector errors; 3 without Docker.
EOF
    exit 2
fi

source "$(dirname "$0")/env.sh"

floor="" apply=0 risky=0 only=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --floor) floor="$2"; shift 2 ;;
        --apply) apply=1; shift ;;
        --allow-risky) risky=1; shift ;;
        --only) only="$2"; shift 2 ;;
        *) phpm_die "$PHPM_EXIT_TOOL_ERROR" "unknown option: $1" ;;
    esac
done
[[ "$floor" =~ ^[0-9]+\.[0-9]+ ]] || phpm_die "$PHPM_EXIT_TOOL_ERROR" "--floor must look like 8.5"

phpm_require_docker
[[ -x "$PHPM_CACHE_DIR/tools/vendor/bin/rector" ]] || "$PHPM_SKILL_DIR/scripts/tools.sh" >/dev/null

IFS=. read -r major minor _ <<<"$floor"
php_set="php${major}${minor}"
php_id=$(( major * 10000 + minor * 100 ))

skip="
        // Risky rules: behaviour or public-API changes. See references/rector.md.
        \\Rector\\Php70\\Rector\\FuncCall\\RandomFunctionRector::class,
        \\Rector\\Php71\\Rector\\FuncCall\\RemoveExtraParametersRector::class,
        \\Rector\\Php80\\Rector\\Switch_\\ChangeSwitchToMatchRector::class,
        \\Rector\\Php80\\Rector\\Class_\\ClassPropertyAssignToConstructorPromotionRector::class,
        \\Rector\\CodeQuality\\Rector\\ClassMethod\\OptionalParametersAfterRequiredRector::class,
        \\Rector\\Php81\\Rector\\Property\\ReadOnlyPropertyRector::class,
        \\Rector\\Php82\\Rector\\Class_\\ReadOnlyClassRector::class,
        \\Rector\\Php83\\Rector\\Class_\\ReadOnlyAnonymousClassRector::class,
        \\Rector\\Php83\\Rector\\ClassConst\\AddTypeToConstRector::class,
        \\Rector\\Php85\\Rector\\Class_\\SleepToSerializeRector::class,
        \\Rector\\Php85\\Rector\\Class_\\WakeupToUnserializeRector::class,"
[[ $risky -eq 1 ]] && skip=""

cat > "$PHPM_STATE_DIR/rector.php" <<EOF
<?php
// Generated by php-migrate/scripts/rector.sh — regenerated on every run.
declare(strict_types=1);

require '/skill/scripts/lib/paths.php';

use Rector\Config\RectorConfig;

return RectorConfig::configure()
    ->withPaths(array_map(fn (string \$path): string => '/app/' . \$path, phpm_paths('/app')))
    ->withPhpVersion($php_id)
    ->withPhpSets($php_set: true)
    ->withComposerBased(phpunit: true)
    ->withAttributesSets(phpunit: true)
    ->withCache('/state/rector-cache')
    ->withSkip([$skip
        '*/vendor/*',
    ]);
EOF

args=(process --config /state/rector.php --output-format=json --no-progress-bar)
[[ $apply -eq 0 ]] && args+=(--dry-run)
[[ -n "$only" ]] && args+=(--only "$only")

run_pass() { # <report name>: run Rector once, print its summary, return the summary's exit code
    phpm_run "$PHPM_TOOLS_PHP" php -d memory_limit=-1 /cache/tools/vendor/bin/rector "${args[@]}" \
        >"$PHPM_STATE_DIR/reports/$1.json" 2>"$PHPM_STATE_DIR/reports/$1.stderr"
    phpm_run "$PHPM_TOOLS_PHP" php /skill/scripts/lib/summarize-rector.php "/state/reports/$1.json"
}

set +e
if [[ $apply -eq 0 ]]; then
    run_pass rector
    code=$?
    [[ $code -eq 2 ]] && tail -n 20 "$PHPM_STATE_DIR/reports/rector.stderr" >&2
    exit "$code"
fi

# Apply until a pass changes nothing: files with syntax PHP 8 cannot analyse (e.g. `$s{0}`) get no
# class scope, so scope-based rules (Php4ConstructorRector, ...) only fire on a later pass.
max_passes=5
printf '{"passes": ['
for (( pass = 1; pass <= max_passes; pass++ )); do
    (( pass > 1 )) && printf ','
    run_pass "rector-apply-$pass"
    code=$?
    if [[ $code -eq 2 ]]; then
        printf '], "converged": false}\n'
        tail -n 20 "$PHPM_STATE_DIR/reports/rector-apply-$pass.stderr" >&2
        exit 2
    fi
    [[ $code -eq 0 ]] && break
done
if [[ $code -eq 0 ]]; then
    printf '], "converged": true}\n'
    exit "$PHPM_EXIT_OK"
fi
printf '], "converged": false}\n'
phpm_log "Rector still changes files after $max_passes passes; inspect <state>/reports/rector-apply-*.json"
exit "$PHPM_EXIT_FINDINGS"
